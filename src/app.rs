    fn toast(&mut self, ctx: &egui::Context, msg: impl Into<String>, error: bool) {
        self.toast = Some((msg.into(), error, ctx.input(|i| i.time)));
    }

    fn host(&self, id: &str) -> Option<&Host> {
        self.inventory.hosts.iter().find(|h| h.id == id)
    }

    // -----------------------------------------------------------------------
    // Persistence

    fn poll_save(&mut self, ctx: &egui::Context) {
        if let Some(h) = &self.saving {
            if h.is_finished() {
                let h = self.saving.take().unwrap();
                let failed = match h.join() {
                    Ok(Ok(())) => None,
                    Ok(Err(e)) => Some(format!("Could not save vault, retrying: {e}")),
                    Err(_) => Some("Could not save vault, retrying: save thread panicked".to_string()),
                };
                if let Some(msg) = failed {
                    self.toast(ctx, msg, true);
                    // Keep the changes pending and retry in about five seconds.
                    self.dirty = true;
                    self.dirty_seen = Some(ctx.input(|i| i.time) + 4.0);
                }
            }
        }
        let now = ctx.input(|i| i.time);
        if self.dirty {
            let seen = *self.dirty_seen.get_or_insert(now);
            // Coalesce bursts of edits (typing a note) into one save per second.
            if now - seen < 1.0 {
                ctx.request_repaint_after(std::time::Duration::from_millis(1050));
                return;
            }
        }
        if self.dirty && self.saving.is_none() {
            self.dirty_seen = None;
            if let Some(pw) = &self.password {
                let pw = pw.clone();
                let inv = self.inventory.clone();
                self.dirty = false;
                self.saving = Some(std::thread::spawn(move || store::save(&pw, &inv)));
            }
        }
    }

    /// Waits for any in-flight save, then saves synchronously if needed.
    /// Returns false if changes could not be written.
    fn flush_save(&mut self) -> bool {
        if let Some(h) = self.saving.take() {
            if !matches!(h.join(), Ok(Ok(()))) {
                self.dirty = true;
            }
        }
        if self.dirty {
            if let Some(pw) = &self.password {
                if store::save(pw, &self.inventory).is_err() {
                    return false;
                }
                self.dirty = false;
            }
        }
        true
    }

    fn lock_now(&mut self, ctx: &egui::Context) {
        if !self.flush_save() {
            self.toast(ctx, "Locked, but the last changes could not be saved to the vault file.", true);
        }
        self.dirty = false;
        self.dirty_seen = None;
        self.password = None;
        self.inventory = Inventory::default();
        self.host_form = None;
        self.palette = None;
        self.credential_form = None;
        self.new_key_form = None;
        self.tunnel_form = None;
        self.note_selected = None;
        self.pw_change = PasswordChange::default();
        self.lock = Some(LockScreen::unlock());
    }

    // -----------------------------------------------------------------------
    // Actions

    fn apply(&mut self, ctx: &egui::Context, actions: Vec<Action>) {
        for a in actions {
            match a {
                Action::Connect(id, proto) => self.connect(ctx, &id, proto),
                Action::OpenLocal(shell) => {
                    let restart = Restart::Local(shell.clone());
                    match Terminal::local(&shell, ctx) {
                        Ok(term) => {
                            let label = term.title.clone();
                            self.open_session(Pane::new(label, icon::TERMINAL, term).restarting(restart));
                        }
                        Err(e) => self.open_failed(ctx, shell.clone(), icon::TERMINAL, restart, &format!("Could not start {shell}: {e}")),
                    }
                }
                Action::NewHost(folder) => {
                    let host = Host {
                        id: Host::new_id(),
                        name: String::new(),
                        address: String::new(),
                        port: 22,
                        user: String::new(),
                        protocols: vec![Protocol::Ssh],
                        folder: folder.unwrap_or_default(),
                        favorite: false,
                        kind: HostKind::Server,
                        tags: Vec::new(),
                        last_connected: None,
                        credential_id: None,
                        password: None,
                        rdp_port: crate::model::default_rdp_port(),
                        rdp_fingerprint: None,
                    };
                    self.host_form = Some(HostForm::new(host, true));
                }
                Action::EditHost(id) => {
                    if let Some(h) = self.host(&id).cloned() {
                        self.host_form = Some(HostForm::new(h, false));
                    }
                }
                Action::DeleteHost(id) => {
                    if let Some(h) = self.host(&id).cloned() {
                        let mut f = HostForm::new(h, false);
                        f.confirm_delete = true;
                        self.host_form = Some(f);
                    }
                }
                Action::Duplicate(id) => {
                    if let Some(h) = self.host(&id).cloned() {
                        let mut copy = h;
                        copy.id = Host::new_id();
                        copy.name = format!("{} copy", copy.name);
                        copy.favorite = false;
                        copy.last_connected = None;
                        self.host_form = Some(HostForm::new(copy, true));
                    }
                }
                Action::ToggleFavorite(id) => {
                    if let Some(h) = self.inventory.hosts.iter_mut().find(|h| h.id == id) {
                        h.favorite = !h.favorite;
                        self.dirty = true;
                    }
                }
                Action::SelectTab(i) => {
                    self.active = i.filter(|i| *i < self.sessions.len());
                    if self.active.is_some() {
                        self.focus_active = true;
                    } else {
                        self.page = Page::Home;
                    }
                }
                Action::CloseTab(i) => {
                    if i < self.sessions.len() {
                        let keys: Vec<Credential> = self.sessions[i].panes.iter_mut().filter_map(|p| p.pending_key.take()).collect();
                        for k in keys {
                            self.finish_key(ctx, k);
                        }
                        self.sessions.remove(i);
                        self.active = match self.active {
                            Some(a) if a == i => {
                                if self.sessions.is_empty() {
                                    None
                                } else {
                                    Some(i.min(self.sessions.len() - 1))
                                }
                            }
                            Some(a) if a > i => Some(a - 1),
                            other => other,
                        };
                        self.focus_active = self.active.is_some();
                    }
                }
                Action::Reconnect(i) => {
                    if let Some(id) = self.sessions.get(i).map(|s| s.focus) {
                        self.apply(ctx, vec![Action::ReconnectPane(i, id)]);
                    }
                }
                Action::ReconnectPane(t, pid) => {
                    let restart = self.sessions.get(t).and_then(|s| s.panes.iter().find(|p| p.id == pid)).map(|p| p.restart.clone());
                    let Some(restart) = restart.filter(|r| !matches!(r, Restart::Nothing)) else { continue };
                    if let Some(mut p) = self.launch_pane(ctx, &restart) {
                        if let Some(s) = self.sessions.get_mut(t) {
                            if let Some(slot) = s.pane_mut(pid) {
                                // Same place in the layout, new program.
                                p.id = pid;
                                *slot = p;
                                s.focus_changed = true;
                            }
                        }
                        self.active = Some(t);
                    }
                }
                Action::SplitPane(t, dir) => {
                    let Some(restart) = self.sessions.get(t).map(|s| split_target(&s.focused().restart)) else { continue };
                    if let Some(p) = self.launch_pane(ctx, &restart) {
                        if let Some(s) = self.sessions.get_mut(t) {
                            s.add(p, dir);
                        }
                        self.active = Some(t);
                    }
                }
                Action::ClosePane(t, pid) => {
                    let Some(s) = self.sessions.get_mut(t) else { continue };
                    match s.take(pid) {
                        Some(mut p) => {
                            if let Some(k) = p.pending_key.take() {
                                self.finish_key(ctx, k);
                            }
                        }
                        None => self.apply(ctx, vec![Action::CloseTab(t)]),
                    }
                }
                Action::FocusPane(t, nav) => {
                    if let Some(s) = self.sessions.get_mut(t) {
                        let area = self.pane_area.unwrap_or(Rect::from_min_size(Pos2::ZERO, Vec2::new(1000.0, 700.0)));
                        if let Some(id) = s.layout.neighbor(area, s.focus, nav) {
                            s.set_focus(id);
                        }
                    }
                }
                Action::CyclePane(t, forward) => {
                    if let Some(s) = self.sessions.get_mut(t) {
                        s.cycle(forward);
                    }
                }
                Action::SwapPane(t, forward) => {
                    if let Some(s) = self.sessions.get_mut(t) {
                        s.swap_with(forward);
                    }
                }
                Action::SwapPanes(t, a, b) => {
                    if let Some(s) = self.sessions.get_mut(t) {
                        s.layout.swap(a, b);
                    }
                }
                Action::ResizePane(t, nav) => {
                    if let Some(s) = self.sessions.get_mut(t) {
                        let focus = s.focus;
                        s.layout.resize(focus, nav, 0.05);
                    }
                }
                Action::ZoomPane(t) => {
                    if let Some(s) = self.sessions.get_mut(t) {
                        s.zoom = !s.zoom && s.panes.len() > 1;
                        s.focus_changed = true;
                    }
                }
                Action::BreakPane(t) => {
                    let pane = self.sessions.get_mut(t).and_then(|s| {
                        let id = s.focus;
                        s.take(id)
                    });
                    if let Some(p) = pane {
                        self.open_session(p);
                    }
                }
                Action::SendToPane(t, bytes) => {
                    if let Some(s) = self.sessions.get_mut(t) {
                        s.focused_mut().term.send(&bytes);
                    }
                }
                Action::ToggleSidebar => self.sidebar_open = !self.sidebar_open,
                Action::ToggleFolder(p) => {
                    if !self.collapsed.remove(&p) {
                        self.collapsed.insert(p);
                    }
                }
                Action::ToggleHomeFolder(p) => {
                    if !self.home_collapsed.remove(&p) {
                        self.home_collapsed.insert(p);
                    }
                }
                Action::Page(p) => {
                    self.page = p;
                    self.active = None;
                }
                Action::Lock => self.lock_now(ctx),
                Action::OpenPalette => self.palette = Some(Palette { query: String::new(), selected: 0, opened: true }),
                Action::NewNote(host_id) => {
                    let note = crate::model::Note {
                        id: Host::new_id(),
                        title: String::new(),
                        body: String::new(),
                        host_id,
                        updated: now(),
                    };
                    self.note_selected = Some(note.id.clone());
                    self.inventory.notes.insert(0, note);
                    self.dirty = true;
                    self.page = Page::Notes;
                    self.active = None;
                }
                Action::PasteNote(id, tab) => {
                    let body = self.inventory.notes.iter().find(|n| n.id == id).map(|n| n.body.clone());
                    if let (Some(body), Some(s)) = (body, self.sessions.get_mut(tab)) {
                        s.focused_mut().term.paste(&body);
                        s.focus_changed = true;
                        self.active = Some(tab);
                        self.focus_active = true;
                    }
                }
                Action::NewTunnel(host_id) => self.tunnel_form = Some(TunnelForm::new_for(host_id, &self.inventory)),
                Action::EditTunnel(id) => {
                    if let Some(t) = self.inventory.tunnels.iter().find(|t| t.id == id) {
                        self.tunnel_form = Some(TunnelForm::edit(t.clone()));
                    }
                }
                Action::StartTunnel(id) => self.start_tunnel(ctx, &id),
                Action::StopTunnel(id) => {
                    self.tunnels_running.remove(&id);
                }
                Action::InstallKey(host_id) => self.install_key(ctx, &host_id),
                Action::GenerateKey(name, comment) => self.generate_key(ctx, &name, &comment),
                Action::CopyPassword(id) => {
                    let pw = self.host(&id).and_then(|h| self.password_for(h)).map(|p| p.expose().to_string());
                    match pw {
                        Some(pw) => {
                            ctx.copy_text(pw);
                            self.toast(ctx, "Password copied to the clipboard.", false);
                        }
                        None => self.toast(ctx, "No password is saved for this host.", true),
                    }
                }
            }
        }
    }

    fn open_session(&mut self, p: Pane) {
        self.sessions.push(Session::new(p));
        self.active = Some(self.sessions.len() - 1);
        self.focus_active = true;
    }

    /// Starts `restart` the way a new tab would, but hands back the pane
    /// instead (for splits and reconnecting one pane).
    fn launch_pane(&mut self, ctx: &egui::Context, restart: &Restart) -> Option<Pane> {
        let (before, active, focus) = (self.sessions.len(), self.active, self.focus_active);
        match restart.clone() {
            Restart::Host(id, proto) => self.connect(ctx, &id, proto),
            Restart::Local(shell) => self.apply(ctx, vec![Action::OpenLocal(shell)]),
            Restart::Nothing => self.apply(ctx, vec![Action::OpenLocal(terminal::default_shell())]),
        }
        let pane = if self.sessions.len() > before { self.sessions.pop().and_then(|mut s| s.panes.pop()) } else { None };
        self.active = active;
        self.focus_active = focus;
        pane
    }

    fn connect(&mut self, ctx: &egui::Context, id: &str, proto: Protocol) {
        let Some(h) = self.host(id).cloned() else {
            self.toast(ctx, "That host was deleted.", true);
            return;
        };
        let result = match proto {
            Protocol::Ssh | Protocol::Sftp => {
                let program = if proto == Protocol::Ssh { "ssh" } else { "sftp" };
                self.ssh_spec(&h, program, Vec::new()).and_then(|spec| Terminal::openssh(spec, h.name.clone(), ctx))
            }
            Protocol::Rdp => {
                self.connect_rdp(ctx, &h);
                return;
            }
            Protocol::Local => Terminal::local(&terminal::default_shell(), ctx),
        };
        let label = if proto == Protocol::Sftp { format!("{} · sftp", h.name) } else { h.name.clone() };
        let restart = Restart::Host(h.id.clone(), proto);
        match result {
            Ok(term) => {
                self.open_session(Pane::new(label, widgets::kind_icon(h.kind), term).restarting(restart));
                if let Some(h) = self.inventory.hosts.iter_mut().find(|x| x.id == id) {
                    h.last_connected = Some(now());
                    self.dirty = true;
                }
            }
            Err(e) => self.open_failed(ctx, label, widgets::kind_icon(h.kind), restart, &format!("Could not connect to {}: {e}", h.name)),
        }
    }

    /// A tab showing why something could not start; Enter retries it.
    fn open_failed(&mut self, ctx: &egui::Context, label: String, glyph: &'static str, restart: Restart, error: &str) {
        match Terminal::failed(label.clone(), error, ctx) {
            Ok(term) => self.open_session(Pane::new(label, glyph, term).restarting(restart)),
            Err(_) => self.toast(ctx, error.to_string(), true),
        }
    }

    /// The host's credential; an error if it points at a deleted one.
    fn credential_of(&self, h: &Host) -> anyhow::Result<Option<&Credential>> {
        match &h.credential_id {
            None => Ok(None),
            Some(_) => self
                .inventory
                .credential(h.credential_id.as_ref())
                .map(Some)
                .ok_or_else(|| anyhow::anyhow!("the credential assigned to {} was deleted; pick another in Edit host", h.name)),
        }
    }

    /// The user to sign in as: the host's own, else the credential's.
    fn user_for(&self, h: &Host) -> String {
        if !h.user.is_empty() {
            return h.user.clone();
        }
        self.inventory.credential(h.credential_id.as_ref()).map(|c| c.username.clone()).unwrap_or_default()
    }

    /// The host's own password, else the credential's.
    fn password_for(&self, h: &Host) -> Option<Secret> {
        h.password.clone().or_else(|| self.inventory.credential(h.credential_id.as_ref()).and_then(|c| c.password.clone()))
    }

    /// Builds the OpenSSH invocation for a host, resolving its credential.
    fn ssh_spec(&self, h: &Host, program: &'static str, options: Vec<String>) -> anyhow::Result<SshSpec> {
        let cred = self.credential_of(h)?;
        let mut spec = SshSpec {
            program,
            user: self.user_for(h),
            address: h.address.clone(),
            port: h.port,
            identity: None,
            options,
            temp_files: Vec::new(),
            secrets: Default::default(),
        };
        if let Some(key) = cred {
            match &key.source {
                Some(KeySource::File(path)) => {
                    let path = pages::expand_home(path);
                    if !path.is_file() {
                        anyhow::bail!("key file {} not found", path.display());
                    }
                    spec.identity = Some(path);
                }
                Some(KeySource::Embedded(pem)) => {
                    let files = store::write_temp_key(pem, key.public.as_deref())?;
                    spec.identity = Some(files[0].clone());
                    spec.temp_files = files;
                }
                None => {}
            }
            if spec.identity.is_some() {
                spec.secrets.passphrase = key.passphrase.clone();
                spec.secrets.key_path = spec.identity.clone();
            }
        }
        spec.secrets.password = self.password_for(h);
        spec.secrets.hosts = vec![h.address.trim_start_matches('[').trim_end_matches(']').to_string()];
        Ok(spec)
    }

    fn connect_rdp(&mut self, ctx: &egui::Context, h: &Host) {
        let label = format!("{} · rdp", h.name);
        let restart = Restart::Host(h.id.clone(), Protocol::Rdp);
        if let Err(e) = self.credential_of(h) {
            self.open_failed(ctx, label, icon::DESKTOP, restart, &format!("Could not connect to {}: {e}", h.name));
            return;
        }
        if self.inventory.settings.rdp_client == crate::model::RdpClient::Builtin {
            let params = crate::rdp_view::Params {
                host: h.address.trim_start_matches('[').trim_end_matches(']').to_string(),
                port: h.rdp_port,
                user: self.user_for(h),
                password: Zeroizing::new(self.password_for(h).map(|p| p.expose().to_string()).unwrap_or_default()),
                known_fingerprint: h.rdp_fingerprint.clone(),
            };
            if params.user.is_empty() || params.password.is_empty() {
                let e = "the built-in client signs in with a saved user name and password: add them in Edit host (or its credential), or pick an external client in Settings → Remote desktop";
                self.open_failed(ctx, label, icon::DESKTOP, restart, &format!("Could not connect to {}: {e}", h.name));
                return;
            }
            let view = crate::rdp_view::RdpView::connect(params, h.name.clone(), ctx);
            self.open_session(Pane::new(label, icon::DESKTOP, view).restarting(restart));
            if let Some(x) = self.inventory.hosts.iter_mut().find(|x| x.id == h.id) {
                x.last_connected = Some(now());
                self.dirty = true;
            }
            return;
        }
        let target = crate::rdp::Target {
            address: h.address.clone(),
            port: h.rdp_port,
            user: self.user_for(h),
            password: self.password_for(h),
            title: h.name.clone(),
        };
        let result = crate::rdp::launch(&target, self.inventory.settings.rdp_client, &store::run_dir()).and_then(|launch| match launch {
            crate::rdp::Launch::Terminal(cmd) => Terminal::spawn(cmd, h.name.clone(), ctx).map(Some),
            crate::rdp::Launch::External(msg) => {
                self.toast(ctx, msg, false);
                Ok(None)
            }
        });
        match result {
            Ok(term) => {
                if let Some(term) = term {
                    self.open_session(Pane::new(label, icon::DESKTOP, term).restarting(restart));
                }
                if let Some(x) = self.inventory.hosts.iter_mut().find(|x| x.id == h.id) {
                    x.last_connected = Some(now());
                    self.dirty = true;
                }
            }
            Err(e) => self.open_failed(ctx, label, icon::DESKTOP, restart, &format!("Could not open RDP to {}: {e}", h.name)),
        }
    }

    fn start_tunnel(&mut self, ctx: &egui::Context, id: &str) {
        let Some(t) = self.inventory.tunnels.iter().find(|t| t.id == id).cloned() else { return };
        let Some(h) = self.host(&t.host_id).cloned() else {
            self.toast(ctx, format!("Tunnel {}: its host was deleted.", t.name), true);
            return;
        };
        let mut options: Vec<String> = ["-N", "-o", "ExitOnForwardFailure=yes", "-o", "ServerAliveInterval=30", "-o", "ServerAliveCountMax=3"]
            .iter()
            .map(|s| s.to_string())
            .collect();
        options.extend(t.ssh_args());
        match self.ssh_spec(&h, "ssh", options).and_then(|spec| Terminal::openssh(spec, t.name.clone(), ctx)) {
            Ok(mut term) => {
                term.exit_notice = false;
                self.tunnels_running.insert(t.id.clone(), term);
            }
            Err(e) => self.toast(ctx, format!("Tunnel {}: {e}", t.name), true),
        }
    }

    fn install_key(&mut self, ctx: &egui::Context, host_id: &str) {
        let Some(h) = self.host(host_id).cloned() else { return };
        let key = self.inventory.credential(h.credential_id.as_ref()).filter(|c| c.source.is_some()).cloned();
        let Some(key) = key else {
            self.toast(ctx, "Pick a credential with an SSH key for this host first (Edit host → Credential).", true);
            return;
        };
        if matches!(key.source, Some(KeySource::Embedded(_))) && key.public.is_none() {
            self.toast(ctx, "This key has no public key stored, so it cannot be installed.", true);
            return;
        }
        match self.ssh_spec(&h, "ssh-copy-id", Vec::new()).and_then(|spec| Terminal::openssh(spec, format!("install key · {}", h.name), ctx)) {
            Ok(term) => self.open_session(Pane::new(format!("install key · {}", h.name), icon::KEY, term)),
            Err(e) => self.toast(ctx, format!("Could not run ssh-copy-id: {e}"), true),
        }
    }

    fn generate_key(&mut self, ctx: &egui::Context, name: &str, comment: &str) {
        let Some(home) = dirs::home_dir() else { return };
        let dir = home.join(".ssh");
        if !dir.exists() {
            let _ = std::fs::create_dir_all(&dir);
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt;
                let _ = std::fs::set_permissions(&dir, std::fs::Permissions::from_mode(0o700));
            }
        }
        let path = dir.join(name);
        // ssh-keygen asks for the passphrase itself, so it never passes through Shellyard.
        let mut cmd = portable_pty::CommandBuilder::new("ssh-keygen");
        cmd.args(["-t", "ed25519", "-C", comment, "-f"]);
        cmd.arg(&path);
        match Terminal::spawn(cmd, format!("new key · {name}"), ctx) {
            Ok(term) => {
                let mut s = Pane::new(format!("new key · {name}"), icon::KEY, term);
                s.pending_key = Some(Credential::key(name, KeySource::File(pages::collapse_home(&path)), None));
                self.open_session(s);
            }
            Err(e) => self.toast(ctx, format!("Could not run ssh-keygen: {e}"), true),
        }
    }

    /// Adds a generated key to the vault once ssh-keygen has finished (or its
    /// pane is closed), if the key file was actually written.
    fn finish_key(&mut self, ctx: &egui::Context, key: Credential) {
        let written = match &key.source {
            Some(KeySource::File(p)) => pages::expand_home(p).is_file(),
            _ => true,
        };
        if written {
            let name = key.name.clone();
            self.inventory.credentials.push(key);
            self.dirty = true;
            self.toast(ctx, format!("Key {name} added. Pick it for a host in Edit host."), false);
        } else {
            self.toast(ctx, format!("ssh-keygen did not create {}; nothing was added.", key.name), true);
        }
    }

