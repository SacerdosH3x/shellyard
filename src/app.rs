/// One terminal or RDP view inside a tab.
struct Pane {
    id: PaneId,
    label: String,
    glyph: &'static str,
    term: View,
    /// A key being generated by ssh-keygen in this tab. It is added to the
    /// vault once the key file exists, so a cancelled run leaves nothing behind.
    pending_key: Option<Credential>,
    /// What Enter (after the program ended) or "Reconnect" starts again.
    restart: Restart,
}

/// What a tab shows.
enum View {
    Term(Box<Terminal>),
    Rdp(Box<crate::rdp_view::RdpView>),
}

impl From<Terminal> for View {
    fn from(t: Terminal) -> Self {
        View::Term(Box::new(t))
    }
}

impl From<crate::rdp_view::RdpView> for View {
    fn from(r: crate::rdp_view::RdpView) -> Self {
        View::Rdp(Box::new(r))
    }
}

impl View {
    fn title(&self) -> &str {
        match self {
            View::Term(t) => &t.title,
            View::Rdp(r) => &r.title,
        }
    }

    fn exited(&self) -> bool {
        match self {
            View::Term(t) => t.exited,
            View::Rdp(r) => r.exited(),
        }
    }

    fn poll(&mut self, ctx: &egui::Context) {
        if let View::Term(t) = self {
            t.poll(ctx);
        }
    }

    fn show(&mut self, ui: &mut Ui) {
        match self {
            View::Term(t) => t.show(ui),
            View::Rdp(r) => r.show(ui),
        }
    }

    fn focus(&self, ctx: &egui::Context) {
        match self {
            View::Term(t) => t.focus(ctx),
            View::Rdp(r) => r.focus(ctx),
        }
    }

    fn paste(&mut self, text: &str) {
        match self {
            View::Term(t) => t.paste(text),
            View::Rdp(r) => r.type_text(text),
        }
    }

    fn send(&mut self, bytes: &[u8]) {
        if let View::Term(t) = self {
            t.write(bytes);
        }
    }

    fn take_restart(&mut self) -> bool {
        match self {
            View::Term(t) => std::mem::take(&mut t.restart_requested),
            View::Rdp(r) => std::mem::take(&mut r.restart_requested),
        }
    }
}

#[derive(Clone)]
enum Restart {
    Host(String, Protocol),
    Local(String),
    Nothing,
}

impl Pane {
    fn new(label: String, glyph: &'static str, term: impl Into<View>) -> Self {
        static NEXT: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(1);
        let id = NEXT.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        Self { id, label, glyph, term: term.into(), pending_key: None, restart: Restart::Nothing }
    }

    fn restarting(mut self, restart: Restart) -> Self {
        self.restart = restart;
        self
    }
}

// Password fields are wiped from memory when the screen goes away.
enum LockScreen {
    Unlock { password: Zeroizing<String>, error: Option<String>, focused: bool },
    Create { password: Zeroizing<String>, confirm: Zeroizing<String>, sample: bool, error: Option<String>, focused: bool },
}

impl LockScreen {
    fn unlock() -> Self {
        LockScreen::Unlock { password: Zeroizing::default(), error: None, focused: false }
    }
}

