#!/usr/bin/env bash
# Writes Formula/shellyard.rb for a published release and pushes it to the
# Homebrew tap (github.com/SacerdosH3x/homebrew-tap). Needs `gh` logged in.
#   scripts/update-tap.sh v0.1.0
set -euo pipefail

REPO="SacerdosH3x/shellyard"
TAP="SacerdosH3x/homebrew-tap"
TAG="${1:?usage: $0 vX.Y.Z}"
VERSION="${TAG#v}"

sum() {
  gh release download "$TAG" --repo "$REPO" --pattern "shellyard-$VERSION-$1.tar.gz.sha256" --output - | cut -d' ' -f1
}
MAC=$(sum macos-universal)
LINUX_X64=$(sum linux-x86_64)
LINUX_ARM=$(sum linux-aarch64)
URL="https://github.com/$REPO/releases/download/$TAG"

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
gh repo clone "$TAP" "$WORK/tap" -- --quiet
mkdir -p "$WORK/tap/Formula"
cat > "$WORK/tap/Formula/shellyard.rb" <<RUBY
# Generated by scripts/update-tap.sh in $REPO. Do not edit by hand.
class Shellyard < Formula
  desc "SSH, SFTP, tunnels and terminals with an encrypted vault"
  homepage "https://github.com/$REPO"
  version "$VERSION"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    url "$URL/shellyard-$VERSION-macos-universal.tar.gz"
    sha256 "$MAC"
  end

  on_linux do
    on_intel do
      url "$URL/shellyard-$VERSION-linux-x86_64.tar.gz"
      sha256 "$LINUX_X64"
    end
    on_arm do
      url "$URL/shellyard-$VERSION-linux-aarch64.tar.gz"
      sha256 "$LINUX_ARM"
    end
  end

  def install
    if OS.mac?
      prefix.install "Shellyard.app"
      bin.write_exec_script prefix/"Shellyard.app/Contents/MacOS/shellyard"
    else
      bin.install "shellyard"
      (share/"applications").install "shellyard.desktop"
      (share/"icons/hicolor/256x256/apps").install "shellyard.png"
    end
  end

  def caveats
    on_macos do
      <<~EOS
        Start Shellyard with \`shellyard\`, or add it to your Applications folder:
          ln -sfn #{opt_prefix}/Shellyard.app ~/Applications/Shellyard.app
      EOS
    end
  end

  test do
    assert_predicate bin/"shellyard", :executable?
  end
end
RUBY
# macOS: a cask, so Shellyard.app lands in /Applications like any other app.
mkdir -p "$WORK/tap/Casks"
cat > "$WORK/tap/Casks/shellyard.rb" <<RUBY
# Generated by scripts/update-tap.sh in $REPO. Do not edit by hand.
cask "shellyard" do
  version "$VERSION"
  sha256 "$MAC"

  url "https://github.com/$REPO/releases/download/v#{version}/shellyard-#{version}-macos-universal.tar.gz"
  name "Shellyard"
  desc "SSH, SFTP, RDP, tunnels and terminals with an encrypted vault"
  homepage "https://github.com/$REPO"

  depends_on macos: ">= :big_sur"

  app "Shellyard.app"
  binary "#{appdir}/Shellyard.app/Contents/MacOS/shellyard"

  # Releases are not signed with an Apple Developer ID yet; without this,
  # Gatekeeper refuses to open the downloaded app.
  postflight do
    system_command "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "#{appdir}/Shellyard.app"]
  end

  caveats "Your vault is kept on uninstall: ~/Library/Application Support/Shellyard"
end
RUBY
cd "$WORK/tap"
if true; then  # always refresh the install instructions
  printf '# Homebrew tap\n\n    brew trust sacerdosh3x/tap\n    brew install --cask sacerdosh3x/tap/shellyard   # macOS: Shellyard.app in /Applications\n    brew install sacerdosh3x/tap/shellyard          # Linux\n\nGenerated from releases of https://github.com/%s.\n' "$REPO" > README.md
fi
git add -A
if git diff --cached --quiet; then echo "tap already up to date"; exit 0; fi
git commit -q -m "shellyard $VERSION"
git push -q origin HEAD
echo "Pushed Formula/shellyard.rb and Casks/shellyard.rb for $TAG to $TAP"
